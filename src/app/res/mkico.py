# Usage: python -I mkico.py <out.ico> <out_icon_data.h>
# Generates msdisp.ico (+ the same bytes as a C++ header for the runtime fallback): a portrait monitor (tall rounded screen) with a USB-blue fill.
import struct, sys

def render(n):
    px = [[(0, 0, 0, 0)] * n for _ in range(n)]
    def inside_rr(x, y, x0, y0, x1, y1, r):
        cx = min(max(x, x0 + r), x1 - r); cy = min(max(y, y0 + r), y1 - r)
        return (x - cx) ** 2 + (y - cy) ** 2 <= r * r
    s = n / 32.0
    bx0, by0, bx1, by1 = 8 * s, 1.5 * s, 24 * s, 27 * s   # bezel (portrait)
    sx0, sy0, sx1, sy1 = 10 * s, 3.5 * s, 22 * s, 25 * s  # screen
    ss = 4
    for y in range(n):
        for x in range(n):
            acc = [0, 0, 0, 0]
            for j in range(ss):
                for i in range(ss):
                    fx = x + (i + 0.5) / ss; fy = y + (j + 0.5) / ss
                    c = None
                    if inside_rr(fx, fy, sx0, sy0, sx1, sy1, 0.8 * s):
                        t = (fy - sy0) / (sy1 - sy0)
                        c = (int(40 + 30 * t), int(140 - 40 * t), int(230 - 30 * t))
                        # rotation arrow hint: white bar near top
                        if sy0 + 3 * s <= fy <= sy0 + 5 * s and sx0 + 3 * s <= fx <= sx1 - 3 * s:
                            c = (235, 245, 255)
                    elif inside_rr(fx, fy, bx0, by0, bx1, by1, 2.0 * s):
                        c = (34, 38, 46)
                    elif 14 * s <= fx <= 18 * s and 27 * s <= fy <= 29.5 * s:
                        c = (60, 64, 72)
                    elif inside_rr(fx, fy, 10 * s, 29 * s, 22 * s, 31 * s, 1.0 * s):
                        c = (60, 64, 72)
                    if c:
                        acc[0] += c[0]; acc[1] += c[1]; acc[2] += c[2]; acc[3] += 255
            cnt = ss * ss
            a = acc[3] // cnt
            if a:
                k = acc[3] // 255
                px[y][x] = (acc[0] // k, acc[1] // k, acc[2] // k, a)
    return px

def bmp(n):
    px = render(n)
    hdr = struct.pack('<IiiHHIIiiII', 40, n, n * 2, 1, 32, 0, 0, 0, 0, 0, 0)
    data = b''.join(struct.pack('BBBB', b, g, r, a) for row in reversed(px) for (r, g, b, a) in row)
    mask_row = ((n + 31) // 32) * 4
    return hdr + data + b'\0' * (mask_row * n)

sizes = [16, 20, 24, 32, 48]
imgs = [bmp(n) for n in sizes]
out = struct.pack('<HHH', 0, 1, len(sizes))
off = 6 + 16 * len(sizes)
for n, im in zip(sizes, imgs):
    out += struct.pack('<BBBBHHII', n, n, 0, 0, 1, 32, len(im), off)
    off += len(im)
out += b''.join(imgs)
open(sys.argv[1], 'wb').write(out)
if len(sys.argv) > 2:
    lines = ['// GENERATED by src/app/res/mkico.py from the same pixels as res/msdisp.ico. Do not edit.',
             '#pragma once', '', 'namespace msdisp {', '',
             'inline constexpr unsigned char kAppIconIco[] = {']
    for i in range(0, len(out), 20):
        lines.append('    ' + ' '.join('0x%02x,' % b for b in out[i:i + 20]))
    lines += ['};', '', '}  // namespace msdisp', '']
    open(sys.argv[2], 'w', newline='\n').write('\n'.join(lines))
